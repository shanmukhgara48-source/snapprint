const Map<String, String> kCategoryBannerImages = {
  'photo_prints':
      'https://images.unsplash.com/photo-1516035069371-29a1b244cc32?auto=format&fit=crop&w=800&q=80',
  'photo_books':
      'https://images.unsplash.com/photo-1481627834876-b7833e8f5570?auto=format&fit=crop&w=800&q=80',
  'frames_wall_decor':
      'https://images.unsplash.com/photo-1513519245088-0e12902e35a6?auto=format&fit=crop&w=800&q=80',
  'personalized_gifts':
      'https://images.unsplash.com/photo-1544787219-7f47ccb76574?auto=format&fit=crop&w=800&q=80',
};

String resolveProductImage(String productId, String categoryId) {
  final url = kProductImages[productId];
  if (url != null && url.isNotEmpty) return url;
  return kCategoryBannerImages[categoryId] ?? '';
}

/// Derives the categoryId from the product ID prefix (pp_ / pb_ / fw_ / pg_)
String categoryFromProductId(String productId) {
  if (productId.startsWith('pp_')) return 'photo_prints';
  if (productId.startsWith('pb_')) return 'photo_books';
  if (productId.startsWith('fw_')) return 'frames_wall_decor';
  if (productId.startsWith('pg_')) return 'personalized_gifts';
  return '';
}

/// Resolves the best catalog image for a product using ID → category fallback.
String resolveCartProductImage(String productId) =>
    resolveProductImage(productId, categoryFromProductId(productId));
